// ============================================================================
//  assign_eq_misuse.v —— 把赋值误写成比较
//  GROUND TRUTH: R012@13
//
//  `assign y == a;` 里的 `==` 是比较运算符，整条语句是"表达式语句"而不是赋值，
//  于是 y 从未被驱动（悬空）。
// ============================================================================
module assign_eq_misuse (
    input  wire       a,
    output wire       y
);

    assign y == a;

endmodule
